import os,psycopg2
conn=psycopg2.connect(host=os.getenv('DB_HOST','localhost'), port=os.getenv('DB_PORT','5432'), database=os.getenv('DB_NAME','postgres'), user=os.getenv('DB_USER','postgres'), password=os.getenv('DB_PASSWORD','root'))
cur=conn.cursor()
cur.execute("SELECT column_name, data_type FROM information_schema.columns WHERE table_name='document_chunks'")
print('columns:', cur.fetchall())
cur.execute("SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'document_chunks'::regclass")
print('constraints:', cur.fetchall())
cur.execute("SELECT indexname, indexdef FROM pg_indexes WHERE tablename='document_chunks'")
print('indexes:', cur.fetchall())
cur.close(); conn.close()
